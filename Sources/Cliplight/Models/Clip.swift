import Foundation
import CryptoKit

struct Clip: Identifiable, Codable, Equatable {
    enum Kind: String, Codable, CaseIterable {
        case text, image, files
        var symbol: String {
            switch self { case .text: return "text.alignleft"; case .image: return "photo"; case .files: return "doc" }
        }
        var label: String { rawValue.capitalized }
    }
    var id = UUID()
    var createdAt = Date()
    var lastUsedAt = Date()
    var kind: Kind
    var text: String
    var data: Data?
    var richText: Data?
    var source: String
    var sourceBundleID: String?
    var isPinned = false
    /// Set for one-time codes and password-like text; the clip is deleted after this date.
    var expiresAt: Date?
    /// Set when the clip is a saved snippet. Snippets never expire and are found by name.
    var snippetName: String?
    /// Text found in an image clip by on-device text recognition, used for search.
    var recognizedText: String?
    /// When the clip was last pinned or saved as a snippet. Sync uses it so the latest change wins.
    var keptAt: Date?

    var isSnippet: Bool { snippetName != nil }
    var isKept: Bool { isPinned || isSnippet }
    var keptSince: Date { keptAt ?? createdAt }

    var fingerprint: String {
        var bytes = Data(kind.rawValue.utf8)
        bytes.append(Data(text.utf8))
        if let data { bytes.append(data) }
        return SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
    }
    var title: String {
        if let snippetName { return snippetName }
        if kind == .image { return text.isEmpty ? "Copied image" : text }
        if kind == .files { return fileURLs.first?.lastPathComponent ?? "Copied files" }
        let line = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? "Empty text"
        return line.trimmingCharacters(in: .whitespaces)
    }
    var fileURLs: [URL] {
        guard kind == .files else { return [] }
        return text.split(separator: "\n").compactMap { URL(string: String($0)) }
    }
    var searchText: String { "\(snippetName ?? "") \(text) \(recognizedText ?? "") \(source) \(kind.label)" }
    var byteCount: Int { text.utf8.count + (data?.count ?? 0) + (richText?.count ?? 0) }
    var detail: String {
        switch kind {
        case .text: return "\(text.count.formatted()) characters"
        case .image: return ByteCountFormatter.string(fromByteCount: Int64(data?.count ?? 0), countStyle: .file)
        case .files: return "\(fileURLs.count) file\(fileURLs.count == 1 ? "" : "s")"
        }
    }
    func isExpired(at now: Date = Date()) -> Bool { expiresAt.map { $0 <= now } ?? false }
}

/// How long ordinary (unpinned) history is kept.
enum Retention: Int, CaseIterable, Identifiable {
    case day = 1, week = 7, month = 30, year = 365, forever = 0
    var id: Int { rawValue }
    var title: String {
        switch self {
        case .day: return "One Day"
        case .week: return "One Week"
        case .month: return "One Month"
        case .year: return "One Year"
        case .forever: return "Forever"
        }
    }
    var interval: TimeInterval? { self == .forever ? nil : TimeInterval(rawValue) * 86_400 }
}

enum ClipRules {
    /// Hard safety limits. History is otherwise bounded by the chosen retention.
    static let maxItems = 5_000
    static let maxBytes = 512 * 1_024 * 1_024
    static let sensitiveMarkers: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "org.nspasteboard.ClipboardViewerType"
    ]
    static let passwordManagers = ["1password", "onepassword", "bitwarden", "lastpass", "dashlane", "keepass", "keychainaccess", "com.apple.passwords"]

    static func shouldSkip(types: [String], sourceID: String?, ignored: Set<String> = [], skipPasswordManagers: Bool = true) -> Bool {
        if !Set(types).isDisjoint(with: sensitiveMarkers) { return true }
        guard let sourceID else { return false }
        if ignored.contains(sourceID) { return true }
        let source = sourceID.lowercased()
        return skipPasswordManagers && passwordManagers.contains { source.contains($0) }
    }
    /// Snippets, then pins, then most recently used.
    static func ordered(_ items: [Clip]) -> [Clip] {
        items.sorted {
            if $0.isSnippet != $1.isSnippet { return $0.isSnippet }
            if $0.isPinned != $1.isPinned { return $0.isPinned }
            return $0.lastUsedAt > $1.lastUsedAt
        }
    }
    static func trimmed(_ items: [Clip], retention: Retention = .forever, now: Date = Date()) -> [Clip] {
        var bytes = 0
        let cutoff = retention.interval.map { now.addingTimeInterval(-$0) }
        return ordered(items).filter { clip in
            if clip.isExpired(at: now) { return false }
            if !clip.isKept, let cutoff, clip.lastUsedAt < cutoff { return false }
            // Kept entries are still bounded by the total storage budget.
            guard bytes + clip.byteCount <= maxBytes else { return false }
            bytes += clip.byteCount
            return true
        }.prefix(maxItems).map { $0 }
    }
    static func matching(_ items: [Clip], query: String) -> [Clip] {
        let terms = query.split(whereSeparator: \.isWhitespace).map(String.init)
        let matches = ordered(items).filter { item in
            terms.allSatisfy { item.searchText.localizedStandardContains($0) }
        }
        guard let first = terms.first else { return matches }
        // A snippet whose name starts with the query jumps to the top, like a keyword.
        let keyword = matches.filter { $0.snippetName?.lowercased().hasPrefix(first.lowercased()) == true }
        return keyword + matches.filter { item in !keyword.contains { $0.id == item.id } }
    }
}
